// addressDetailAttrTypes アドレス詳細情報のAttributeType定義.
var addressDetailAttrTypes = map[string]attr.Type{
	"addr":                types.StringType,
	"version":             types.Int64Type,
	"os_ext_ips_type":     types.StringType,
	"os_ext_ips_mac_addr": types.StringType,
}

func NewInstanceResource() resource.Resource {
	return &instanceResource{}
}

type instanceResource struct {
	client *service.ConohaClient
}

// リクエストパラメータ：作成時に指定可能なパラメータのみ.
type instanceResourceModel struct {
	Id              types.String `tfsdk:"id"`                // インスタンスID
	FlavorRef       types.String `tfsdk:"flavor_id"`         // フレーバーID
	BlockDevice     types.List   `tfsdk:"block_device"`      // ブロックデバイスマッピング
	AdminPass       types.String `tfsdk:"admin_pass"`        // 管理者パスワード
	KeyName         types.String `tfsdk:"key_name"`          // SSHキーペア名
	SecurityGroup   types.List   `tfsdk:"security_group"`    // セキュリティグループ
	InstanceNameTag types.String `tfsdk:"instance_name_tag"` // インスタンス名
	UserData        types.String `tfsdk:"user_data"`         // ユーザーデータ
	PowerState      types.String `tfsdk:"power_state"`       // 電源状態
	Status          types.String `tfsdk:"status"`            // インスタンスのステータス
	Addresses       types.Map    `tfsdk:"addresses"`         // ネットワークアドレス
}

// BlockDeviceMappingV2モデル.
type blockDeviceModel struct {
	UUID types.String `tfsdk:"uuid"`
}

// SecurityGroupモデル.
type securityGroupModel struct {
	Name types.String `tfsdk:"name"`
}

