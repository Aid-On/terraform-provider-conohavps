// ヘルパー関数：Addressesのみを更新.
func (r *instanceResource) updateAddressesFromInstance(ctx context.Context, data *instanceResourceModel, instance interface{}) {
	server, ok := instance.(*servers.Server)
	if !ok {
		tflog.Error(ctx, "Type assertion failed: servers.Server.", map[string]any{
			"received_type": fmt.Sprintf("%T", instance),
		})
		return
	}

	// Addressesの処理（ネットワークアドレス情報）
	addressMapValues := make(map[string]attr.Value)
	if len(server.Addresses) > 0 {
		for netName, addrs := range server.Addresses {
			if addrSlice, ok := addrs.([]interface{}); ok && len(addrSlice) > 0 {
				addrObjects := make([]attr.Value, len(addrSlice))
				for i, addr := range addrSlice {
					if addrMap, ok := addr.(map[string]interface{}); ok {
						addrValue := ""
						if a, ok := addrMap["addr"]; ok {
							addrValue = fmt.Sprintf("%v", a)
						}
						version := int64(0)
						if v, ok := addrMap["version"]; ok {
							if vf, ok := v.(float64); ok {
								version = int64(vf)
							}
						}
						osExtIPSType := ""
						if t, ok := addrMap["OS-EXT-IPS:type"]; ok {
							osExtIPSType = fmt.Sprintf("%v", t)
						}
						osExtIPSMACAddr := ""
						if m, ok := addrMap["OS-EXT-IPS-MAC:mac_addr"]; ok {
							osExtIPSMACAddr = fmt.Sprintf("%v", m)
						}

						// addressDetailAttrTypesを使用してObjectValueを構築
						addrObj, _ := types.ObjectValue(
							addressDetailAttrTypes,
							map[string]attr.Value{
								"addr":                types.StringValue(addrValue),
								"version":             types.Int64Value(version),
								"os_ext_ips_type":     types.StringValue(osExtIPSType),
								"os_ext_ips_mac_addr": types.StringValue(osExtIPSMACAddr),
							},
						)
						addrObjects[i] = addrObj
					}
				}

				// addressDetailAttrTypesを再利用してListValueを構築
				addrList, _ := types.ListValue(
					types.ObjectType{
						AttrTypes: addressDetailAttrTypes,
					},
					addrObjects,
				)
				addressMapValues[netName] = addrList
			}
		}

		if len(addressMapValues) > 0 {
			// addressDetailAttrTypesを再利用してMapValueを構築
			addresses, _ := types.MapValue(
				types.ListType{ElemType: types.ObjectType{AttrTypes: addressDetailAttrTypes}},
				addressMapValues,
			)
			data.Addresses = addresses
		}
	}

	tflog.Debug(ctx, "Addresses updated in State.", map[string]any{
		"instance_id":     server.ID,
		"addresses_count": len(addressMapValues),
	})
}

// ヘルパー関数：フレーバー変更処理.
func (r *instanceResource) handleFlavorChange(ctx context.Context, instanceID string, flavorRef string) error {
	// インスタンスの現在の状態を確認
	instance, err := r.client.GetInstance(ctx, instanceID)
	if err != nil {
		return fmt.Errorf("failed to retrieve instance status: %w", err)
	}

	// SHUTOFF状態でなければ停止
	if instance.Status != "SHUTOFF" {
		err := r.client.StopInstance(ctx, instanceID)
		if err != nil {
			return fmt.Errorf("failed to stop instance: %w", err)
		}

		_, err = r.client.WaitForInstanceState(ctx, instanceID, "SHUTOFF", 5*time.Minute)
		if err != nil {
			return fmt.Errorf("failed to wait for instance to stop: %w", err)
		}
	}

	// リサイズを実行
	err = r.client.ResizeInstance(ctx, instanceID, flavorRef)
	if err != nil {
		return fmt.Errorf("failed to resize instance: %w", err)
	}

	// リサイズ完了を待機
	_, err = r.client.WaitForInstanceState(ctx, instanceID, "VERIFY_RESIZE", 10*time.Minute)
	if err != nil {
		revertErr := r.client.RevertResizeInstance(ctx, instanceID)
		if revertErr != nil {
			tflog.Error(ctx, "Failed to revert resize.", map[string]any{
				"instance_id": instanceID,
				"error":       revertErr.Error(),
			})
			return fmt.Errorf("failed to wait for resize verification: %w (failed to revert resize: %w)", err, revertErr)
		}
		return fmt.Errorf("failed to wait for resize verification: %w", err)
	}

	// リサイズを確定
	err = r.client.ConfirmResizeInstance(ctx, instanceID)
	if err != nil {
		return fmt.Errorf("failed to confirm resize: %w", err)
	}

	// 確定後、SHUTOFF状態になるまで待機
	_, err = r.client.WaitForInstanceState(ctx, instanceID, "SHUTOFF", 10*time.Minute)
	if err != nil {
		return fmt.Errorf("failed to wait for instance to become SHUTOFF after resize: %w", err)
	}

	tflog.Debug(ctx, "Flavor changed successfully.", map[string]any{
		"instance_id": instanceID,
		"new_flavor":  flavorRef,
	})

	return nil
}

// ヘルパー関数：電源状態変更処理.
func (r *instanceResource) handlePowerStateChange(ctx context.Context, instanceID string, desiredPowerState string) error {
	instance, err := r.client.GetInstance(ctx, instanceID)
	if err != nil {
		return fmt.Errorf("failed to retrieve instance information: %w", err)
	}
	currentPowerState := instance.Status

	// 既に目的の状態であればスキップ
	if currentPowerState == desiredPowerState {
		tflog.Debug(ctx, "Power state is already in desired state.", map[string]any{
			"instance_id": instanceID,
			"state":       desiredPowerState,
		})
		return nil
	}

	// ACTIVEに変更
	if desiredPowerState == "ACTIVE" {
		if currentPowerState != "ACTIVE" {
			tflog.Debug(ctx, "Starting instance.", map[string]any{
				"instance_id":   instanceID,
				"current_state": currentPowerState,
			})

			// レースコンディション対策として再度状態確認
			latestInstance, err := r.client.GetInstance(ctx, instanceID)
			if err != nil {
				return fmt.Errorf("failed to retrieve latest instance status: %w", err)
			}

			if latestInstance.Status == "ACTIVE" {
				tflog.Debug(ctx, "Instance is already ACTIVE.", map[string]any{
					"instance_id": instanceID,
				})
				return nil
			}

			err = r.client.StartInstance(ctx, instanceID)
			if err != nil {
				return fmt.Errorf("failed to start instance: %w", err)
			}

			_, err = r.client.WaitForInstanceState(ctx, instanceID, "ACTIVE", 10*time.Minute)
			if err != nil {
				return fmt.Errorf("failed to wait for instance to become ACTIVE: %w", err)
			}

			tflog.Debug(ctx, "Instance started successfully.", map[string]any{
				"instance_id": instanceID,
			})
		}
	}

	// SHUTOFFに変更
	if desiredPowerState == "SHUTOFF" {
		if currentPowerState != "SHUTOFF" {
			tflog.Debug(ctx, "Stopping instance.", map[string]any{
				"instance_id":   instanceID,
				"current_state": currentPowerState,
			})

			// レースコンディション対策として再度状態確認
			latestInstance, err := r.client.GetInstance(ctx, instanceID)
			if err != nil {
				return fmt.Errorf("failed to retrieve latest instance status: %w", err)
			}

			if latestInstance.Status == "SHUTOFF" {
				tflog.Debug(ctx, "Instance is already SHUTOFF.", map[string]any{
					"instance_id": instanceID,
				})
				return nil
			}

			err = r.client.StopInstance(ctx, instanceID)
			if err != nil {
				return fmt.Errorf("failed to stop instance: %w", err)
			}

			_, err = r.client.WaitForInstanceState(ctx, instanceID, "SHUTOFF", 10*time.Minute)
			if err != nil {
				return fmt.Errorf("failed to wait for instance to become SHUTOFF: %w", err)
			}

			tflog.Debug(ctx, "Instance stopped successfully.", map[string]any{
				"instance_id": instanceID,
			})
		}
	}

	return nil
}

// keepDeclaredBlockDevices は、サーバーに付いているボリューム（attached）のうち state の block_device に挙がっているもの（declared）だけを
// state の順序で返す. state に無いもの（conohavps_volume_attachment で付けた追加 SSD）は写さない.
// state が空（import 直後）なら、付いているものを全部返す.
func keepDeclaredBlockDevices(declared, attached []string) []string {
	if len(declared) == 0 {
		return attached
	}
	isAttached := make(map[string]bool, len(attached))
	for _, id := range attached {
		isAttached[id] = true
	}
	kept := make([]string, 0, len(declared))
	for _, id := range declared {
		if isAttached[id] {
			kept = append(kept, id)
		}
	}
	return kept
}
